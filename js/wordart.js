/**
 * ボタン用の文字を作る。
 * @param {"single"|"ten"} key
 * @returns {SVGElement}
 */
export function wordArt(key) {
  const a = ART[key];
  const ns = 'http://www.w3.org/2000/svg';
  const svg = document.createElementNS(ns, 'svg');
  const pad = 2.7;   // 線の太さのぶん、外にはみ出して切れないようにする
  svg.setAttribute('viewBox', `${-pad} ${-pad} ${a.w + pad * 2} ${a.h + pad * 2}`);
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('class', 'wa');

  // うしろから、影 → 輪郭 → 本体 の順に重ねる（裏面のロゴと同じ）
  for (const layer of ['s', 'o', 'i']) {
    const g = document.createElementNS(ns, 'g');
    g.setAttribute('class', `wa__${layer}`);
    if (layer === 's') g.setAttribute('transform', 'translate(0 0.5)');
    for (const kind of ['fat', 'thin']) {
      if (!a[kind].length) continue;
      const gk = document.createElementNS(ns, 'g');
      gk.setAttribute('stroke-width', String(layer === 'i' ? W[kind].i : W[kind].o));
      for (const p of a[kind]) {
        const path = document.createElementNS(ns, 'path');
        path.setAttribute('d', p.d);
        path.setAttribute('transform', `translate(${p.x} ${p.y})`);
        gk.append(path);
      }
      g.append(gk);
    }
    svg.append(g);
  }
  return svg;
}
